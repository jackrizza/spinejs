const fs = require('node:fs/promises');
const path = require('node:path');
const { minify } = require('terser');

const root = path.resolve(__dirname, '..');
const coreFiles = [
    'src/fetch.js', 'src/render.js', 'src/component.js',
    'src/state.js', 'src/regions.js', 'src/route.js', 'src/spine.js',
];

async function bundle(files, name, outputDirectory, sourceDirectory = root) {
    const sources = Object.fromEntries(await Promise.all(files.map(async file =>
        [file, (await fs.readFile(path.join(sourceDirectory, file), 'utf8')).replace(/\r\n/g, '\n')]
    )));
    const readable = `/* SpineJS ${name} — generated by npm run build */\n` +
        Object.entries(sources).map(([file, source]) => `\n// ${file}\n${source}\n;`).join('\n');
    const minified = await minify(sources, {
        // These scripts share public constructors and lexical bindings. Keep
        // their top-level names available to scripts loaded after this bundle.
        module: false,
        toplevel: false,
        mangle: { toplevel: false },
        keep_classnames: true,
        keep_fnames: true,
        sourceMap: { filename: `${name}.min.js`, url: `${name}.min.js.map`, includeSources: true },
        format: { preamble: `/* SpineJS ${name} — generated by npm run build */` },
    });
    await Promise.all([
        fs.writeFile(path.join(outputDirectory, `${name}.js`), readable),
        fs.writeFile(path.join(outputDirectory, `${name}.min.js`), minified.code + '\n'),
        fs.writeFile(path.join(outputDirectory, `${name}.min.js.map`), minified.map),
    ]);
    console.log(`${name}.js: ${Buffer.byteLength(readable)} bytes; ${name}.min.js: ${Buffer.byteLength(minified.code) + 1} bytes`);
}

// The framework build reads only src/. It never reads the demo, a consumer
// repository, or consumer configuration and is also used by npm pack.
async function buildFramework(outputDirectory = path.join(root, 'dist'), sourceDirectory = root) {
    await fs.mkdir(outputDirectory, { recursive: true });
    await bundle(coreFiles, 'spine', outputDirectory, sourceDirectory);
}

async function buildExample(outputDirectory = path.join(root, 'dist')) {
    const html = await fs.readFile(path.join(root, 'Example/index.html'), 'utf8');
    const scripts = [...html.matchAll(/<script\s+src="([^"]+)"\s*><\/script>/g)]
        .map(match => path.posix.normalize(path.posix.join('Example', match[1])));
    if (scripts.slice(0, coreFiles.length).join('\n') !== coreFiles.join('\n')) {
        throw new Error('Update coreFiles in scripts/build.cjs to match the core script order in Example/index.html');
    }
    const appFiles = scripts.slice(coreFiles.length);
    if (!appFiles.length || /<script(?!\s+src=)[\s>]/.test(html)) {
        throw new Error('Application scripts must use script src attributes in Example/index.html');
    }
    await fs.mkdir(outputDirectory, { recursive: true });
    await bundle(appFiles, 'app', outputDirectory);

    const page = suffix => {
        let first = true;
        return html.replace(/<script\s+src="[^"]+"\s*><\/script>/g, () => {
            if (!first) return '';
            first = false;
            return `<script src="./spine${suffix}.js"></script>\n    <script src="./app${suffix}.js"></script>`;
        }).replace('Classic scripts: core, custom components, application, then startup.',
                'Generated bundles: framework, then application.');
    };
    await Promise.all([
        fs.writeFile(path.join(outputDirectory, 'index.html'), page('.min')),
        fs.writeFile(path.join(outputDirectory, 'index.debug.html'), page('')),
        fs.cp(path.join(root, 'Example/style'), path.join(outputDirectory, 'style'), { recursive: true }),
        fs.copyFile(path.join(root, 'Example/example_table.json'), path.join(outputDirectory, 'example_table.json')),
    ]);
    console.log(`Built ${outputDirectory}`);
}

async function build(outputDirectory = path.join(root, 'dist')) {
    await buildFramework(outputDirectory);
    await buildExample(outputDirectory);
}

module.exports = { build, buildFramework, buildExample };

if (require.main === module) {
    const run = process.argv.includes('--framework') ? buildFramework : build;
    run().catch(error => {
        console.error(error);
        process.exitCode = 1;
    });
}
