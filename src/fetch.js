function makeid(length) {
    let result = "";
    const characters = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
    while (result.length < length) result += characters.charAt(Math.floor(Math.random() * characters.length));
    return result;
}

class RequestError extends Error {
    constructor(message, { code = "REQUEST_ERROR", status = 0, url = "", response } = {}) {
        super(message);
        this.name = "RequestError";
        Object.assign(this, { code, status, url, response });
    }
}

const requestCacheVersions = new Map();

// The Promise is also a cancellation handle. General requests never persist
// unless cache:true is explicitly selected; SingleFetch opts in for compatibility.
function request(url, options = {}) {
    const { responseType = "json", cache = false, cacheKey = responseType === "json" ? String(url) : `${url}::${responseType}`, storage,
        allowRedirects = false, signal, ...fetchOptions } = options;
    const controller = new AbortController();
    let cancelled = false;
    let activeStorage = null;
    const method = String(fetchOptions.method || "GET").toUpperCase();
    const cacheEnabled = cache && method === "GET" && responseType !== "blob";
    const version = cacheEnabled ? (requestCacheVersions.get(cacheKey) || 0) + 1 : 0;
    if (cacheEnabled) {
        requestCacheVersions.set(cacheKey, version);
        try { activeStorage = storage === undefined ? localStorage : storage; } catch (_) { /* optional cache */ }
    }
    const abortError = () => {
        const error = new Error("Request cancelled");
        error.name = "AbortError";
        return error;
    };
    let rejectCancellation;
    const cancellation = new Promise((resolve, reject) => { rejectCancellation = reject; });
    const abort = () => {
        if (cancelled) return;
        cancelled = true;
        controller.abort();
        rejectCancellation(abortError());
    };
    if (signal) {
        if (signal.aborted) abort();
        else signal.addEventListener("abort", abort, { once: true });
    }
    let result;
    const work = async () => {
        if (!["json", "text", "blob"].includes(responseType)) throw new TypeError(`Unsupported responseType: ${responseType}`);
        if (cancelled) throw abortError();
        if (cacheEnabled && window.navigator.onLine === false) {
            try { return JSON.parse(activeStorage?.getItem(cacheKey) ?? "null"); }
            catch (_) { return null; }
        }
        // FormData boundaries are generated by the browser even if callers
        // accidentally supply a Content-Type header for a multipart body.
        const headers = new Headers(fetchOptions.headers || {});
        if (typeof FormData !== "undefined" && fetchOptions.body instanceof FormData) headers.delete("content-type");
        const response = await fetch(url, { ...fetchOptions, headers, signal: controller.signal });
        if (cancelled) throw abortError();
        result.response = response;
        const status = response.status || 0;
        const failure = (message, code) => new RequestError(message, { code, status, url: response.url || String(url), response });
        if (response.ok === false) throw failure(`HTTP ${status}${response.statusText ? ` ${response.statusText}` : ""}`, "HTTP_ERROR");
        if (response.redirected && !allowRedirects) throw failure("Unexpected redirect; authentication may be required", "AUTH_REDIRECT");
        const contentType = response.headers?.get?.("content-type") || "";
        if (responseType === "json" && contentType && !/\bjson\b|\+json\b/i.test(contentType)) {
            throw failure(`Expected JSON, received ${contentType}`, /html/i.test(contentType) ? "AUTH_HTML" : "RESPONSE_TYPE");
        }
        let data;
        if (status === 204 || status === 205 || String(fetchOptions.method).toUpperCase() === "HEAD") data = null;
        else data = await response[responseType]();
        if (cancelled) throw abortError();
        if (cacheEnabled && requestCacheVersions.get(cacheKey) === version) {
            try { activeStorage?.setItem(cacheKey, JSON.stringify(data)); } catch (_) { /* optional cache */ }
        }
        return data;
    };
    // The fetch await yields until the public Promise is constructed, so metadata is safe
    // even with an immediate controlled/mock fetch implementation.
    result = Promise.race([work(), cancellation]);
    result.dispose = result.abort = abort;
    result.finally(() => signal?.removeEventListener("abort", abort)).catch(() => {});
    return result;
}

class SingleFetch {
    constructor(url, options = {}) {
        const pending = request(url, { cache: true, ...options });
        const result = pending.catch(error => ({ Error: error }));
        result.dispose = result.abort = () => pending.dispose();
        return result;
    }
}

class Resource {
    constructor(url, options = {}) {
        this.url = url;
        this.options = options;
        this.state = new State({ persist: false, initial: {
            status: "idle", loading: false, data: null, error: null, httpStatus: 0
        } });
        this._sequence = 0;
        this._request = null;
        this._disposed = false;
    }
    get(key, fallback) { return this.state.get(key, fallback); }
    subscribe(key, callback) { return this.state.subscribe(key, callback); }
    async refresh(options = {}) {
        if (this._disposed) throw new Error("Resource is disposed");
        const sequence = ++this._sequence;
        this._request?.dispose();
        this.state.set("error", null);
        this.state.set("loading", true);
        this.state.set("status", "loading");
        const pending = request(typeof this.url === "function" ? this.url() : this.url, { ...this.options, ...options });
        this._request = pending;
        try {
            const data = await pending;
            if (this._disposed || sequence !== this._sequence) return;
            this.state.set("data", data);
            this.state.set("httpStatus", pending.response?.status || 0);
            this.state.set("status", data == null || (Array.isArray(data) && !data.length) ? "empty" : "success");
            return data;
        } catch (error) {
            if (!this._disposed && sequence === this._sequence) {
                this.state.set("error", error);
                this.state.set("httpStatus", error.status || 0);
                this.state.set("status", error.name === "AbortError" ? "idle" : "error");
            }
            throw error;
        } finally {
            if (!this._disposed && sequence === this._sequence) {
                this._request = null;
                this.state.set("loading", false);
            }
        }
    }
    retry(options) { return this.refresh(options); }
    dispose() {
        if (this._disposed) return;
        this._disposed = true;
        ++this._sequence;
        this._request?.dispose();
        this._request = null;
        this.state.set("loading", false);
        if (this.state.get("status") === "loading") this.state.set("status", "idle");
    }
}

class Fetch {
    constructor({ url = "", runtime = "", callback = {}, render, loading, error, empty,
        options = {}, isEmpty = data => data == null || (Array.isArray(data) && !data.length) }) {
        Object.assign(this, { url, runtime, callback, renderData: render, loading, error, empty, options, isEmpty });
        this.key = makeid(16);
        this.isNotAComponent = true;
        this._mount = null;
        this.state = new State({ persist: false, initial: { status: "idle", loading: false, data: null, error: null } });
    }

    _disposeChild(owned) {
        if (owned && typeof owned.component.dispose === "function") owned.component.dispose(owned.mount);
    }

    _notifyOutput(mount) {
        const owned = mount.output;
        if (!owned || owned.component._mount !== owned.mount) return;
        try { owned.component._notifyMounted?.(owned.mount); }
        catch (error) { this.dispose(mount); throw error; }
    }

    _notifyMounted(mount = this._mount) {
        if (!mount || this._mount !== mount || mount.mounted) return;
        mount.mounted = true;
        this._notifyOutput(mount);
    }

    async _replace(mount, component, sequence) {
        if (this._mount !== mount || mount.sequence !== sequence) return;
        if (!mount.element) {
            mount.placeholder.mount = mount.placeholder.component._mount;
            mount.element = mount.placeholder.mount && mount.placeholder.mount.element;
        }
        if (!mount.element) return;
        const owned = { component, mount: null };
        mount.pending.add(owned);
        try {
            let rendered;
            try { rendered = component.render(); } finally { owned.mount = component._mount; }
            let element = await rendered;
            if (this._mount !== mount || mount.sequence !== sequence) return;
            // General renderers can return asynchronous component factories.
            if (element && typeof element.render === "function") {
                this._disposeChild(owned);
                owned.component = element;
                try { rendered = element.render(); } finally { owned.mount = element._mount; }
                element = await rendered;
            }
            if (this._mount !== mount || mount.sequence !== sequence) return;
            this._disposeChild(mount.output);
            if (!mount.output) this._disposeChild(mount.placeholder);
            mount.element.replaceChildren(element);
            mount.element.className = "";
            mount.output = owned;
            if (mount.mounted) this._notifyOutput(mount);
        } finally {
            mount.pending.delete(owned);
            if (owned !== mount.output) this._disposeChild(owned);
        }
    }

    async execute(mount = this._mount) {
        if (!mount || this._mount !== mount) return;
        const sequence = ++mount.sequence;
        mount.request?.dispose();
        this.state.set("loading", true);
        this.state.set("status", "loading");
        this.state.set("error", null);
        const pending = request(this.url, { cache: !this.renderData, ...this.options });
        mount.request = pending;
        // A loading renderer can itself await child work. Observe network errors
        // immediately while retaining the original rejection for the catch below.
        pending.catch(() => {});
        try {
            if (this.loading && mount.output) await this._replace(mount, await this.loading(), sequence);
            const data = await pending;
            if (this._mount !== mount || mount.sequence !== sequence) return;
            this.state.set("data", data);
            const empty = this.isEmpty(data);
            this.state.set("status", empty ? "empty" : "success");
            const component = this.renderData
                ? await ((empty && this.empty ? this.empty : this.renderData)(data))
                : new this.callback({ key: this.key, table_data: data }).table();
            if (this._mount !== mount || mount.sequence !== sequence) return;
            await this._replace(mount, component, sequence);
        } catch (error) {
            if (this._mount !== mount || mount.sequence !== sequence) return;
            this.state.set("error", error);
            this.state.set("status", error.name === "AbortError" ? "idle" : "error");
            if (this.error && error.name !== "AbortError") {
                try { await this._replace(mount, await this.error(error), sequence); }
                catch (renderError) { if (this._mount === mount) console.error(renderError); }
            } else if (error.name !== "AbortError") console.error(error);
        } finally {
            if (mount.request === pending) mount.request = null;
            if (this._mount === mount && mount.sequence === sequence) this.state.set("loading", false);
        }
    }

    refresh() { return this.execute(); }
    retry() { return this.execute(); }

    async render() {
        this.dispose();
        const mount = { idle: null, interval: null, request: null, placeholder: null,
            output: null, pending: new Set(), element: null, sequence: 0, mounted: false };
        this._mount = mount;
        try {
            const placeholder = this.renderData
                ? new Div({ key: this.key, children: this.loading ? [this.loading()] : [] })
                : new this.callback({ key: this.key }).placeholder();
            mount.placeholder = { component: placeholder, mount: null };
            const start = () => {
                mount.idle = null;
                if (this._mount !== mount) return;
                if (this.runtime === "" || this.runtime === "slow") this.execute(mount);
                if (this.runtime === "slow") {
                    mount.interval = window.setInterval(() => {
                        if (!mount.request) this.execute(mount);
                    }, 1500);
                }
            };
            mount.idle = typeof window.requestIdleCallback === "function"
                ? { kind: "idle", id: window.requestIdleCallback(start, { timeout: 4000 }) }
                : { kind: "timeout", id: window.setTimeout(start, 0) };
            return placeholder;
        } catch (error) { this.dispose(mount); throw error; }
    }

    dispose(mount = this._mount) {
        if (!mount || this._mount !== mount) return;
        this._mount = null;
        if (mount.idle?.kind === "idle") window.cancelIdleCallback?.(mount.idle.id);
        else if (mount.idle) window.clearTimeout(mount.idle.id);
        if (mount.interval !== null) window.clearInterval(mount.interval);
        mount.request?.dispose();
        if (mount.placeholder && !mount.placeholder.mount) mount.placeholder.mount = mount.placeholder.component._mount;
        this._disposeChild(mount.placeholder);
        this._disposeChild(mount.output);
        for (const owned of mount.pending) this._disposeChild(owned);
        mount.pending.clear();
        this.state.set("loading", false);
        if (this.state.get("status") === "loading") this.state.set("status", "idle");
    }
}
